"""`process` reward: the answer came from the earnings-calendars skill.

The chain is a JSON file the agent can read, and an agent that eyeballs the
straddle can land close enough to pass `outcome` without ever loading the skill.
An early run did exactly that: the trajectory showed only Read and Write. That
is worth failing, because the point of the task is the skill.

Accepts either route into it, the Skill tool or running the script the skill
documents, since which one Claude Code picks is its business and not something
this eval should pin down.

Generated by evals/generate_tasks.py.
"""

import json
from pathlib import Path

from rewardkit import criterion

TRAJECTORY = "/logs/agent/trajectory.json"


def _calls() -> list:
    """Every tool call in the trajectory, or [] when there is none.

    A list rather than a generator so every criterion can fail closed on an
    empty trajectory. A "did not bypass" check is vacuously true when there are
    no calls at all, which handed a no-op run half of `process`; no trajectory
    means no evidence the intended route was taken, so it has to score 0.
    """
    try:
        data = json.loads(Path(TRAJECTORY).read_text())
    except (OSError, json.JSONDecodeError):
        return []
    return [call for step in data.get("steps") or [] for call in step.get("tool_calls") or []]


def _name(call) -> str:
    return str(call.get("function_name") or "")


def _args(call) -> str:
    return json.dumps(call.get("arguments") or {})


SKILL = "earnings-calendars"
SCRIPT = "calendars.py"


@criterion(description="Agent used the earnings-calendars skill or its script")
def used_the_skill(workspace: Path) -> bool:
    """Either the Skill tool or a run of the script the skill documents.

    Deliberately narrow. Matching the skill name anywhere in the arguments also
    matched the reference chain's own path, which contains it, so merely
    reading the input file scored as using the skill.
    """
    for call in _calls():
        if _name(call) == "Skill" and SKILL in _args(call):
            return True
        if SCRIPT in _args(call):
            return True
    return False
