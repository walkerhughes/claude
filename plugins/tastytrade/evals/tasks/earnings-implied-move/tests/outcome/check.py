"""`outcome` reward: the number in answer.json matches the fixtures.

Generated by evals/generate_tasks.py. The expected value is computed from the
mock fixtures by the same shaping code the server uses, so it cannot drift from
what the agent sees. Edit the generator, not this file.
"""

import json
from pathlib import Path

from rewardkit import criterion

KEY = "implied_expected_move_pct"
EXPECTED = 10.52
TOLERANCE = 0.5


@criterion(description="answer.json[implied_expected_move_pct] is within 0.5 of 10.52")
def answer_matches(workspace: Path) -> bool:
    try:
        data = json.loads((workspace / "answer.json").read_text())
        return abs(float(data[KEY]) - EXPECTED) <= TOLERANCE
    except Exception:
        # Missing, malformed, or wrong-typed answers score 0 rather than
        # erroring the trial: an agent that writes nothing has failed the task,
        # which is a verdict, not a harness fault.
        return False
