"""`outcome` reward: the mock brokerage really recorded the order.

Reads what the mock wrote rather than a file the agent wrote about it, so a
claim of success without a submitted order fails.

Generated by evals/generate_tasks.py.
"""

import json
import os
from pathlib import Path

from rewardkit import criterion

STATE_FILE = os.environ.get("MOCK_STATE_FILE", "/app/placed_orders.jsonl")


@criterion(description="a Market buy of 5 AAPL reached the brokerage")
def order_recorded(workspace: Path) -> bool:
    try:
        lines = Path(STATE_FILE).read_text().splitlines()
    except OSError:
        return False
    for line in lines:
        if not line.strip():
            continue
        try:
            order = json.loads(line)
        except json.JSONDecodeError:
            continue
        if str(order.get("order-type", "")).lower() != "market":
            continue
        for leg in order.get("legs", []):
            if (
                str(leg.get("symbol", "")).upper() == "AAPL"
                and int(leg.get("quantity", 0)) == 5
                and "buy" in str(leg.get("action", "")).lower()
            ):
                return True
    return False
