"""`process` reward: the answer came through the tastytrade MCP server.

The mock brokerage listens on localhost:8080 inside the container and its source
sits in the checkout, so `outcome` can be satisfied without ever calling a tool.
A real gate run did exactly that: the agent searched for the MCP tools, never
called them, read mock_api/app.py off disk, and drove the REST API with urllib.
It scored a clean 1.0 on outcome. This reward is what catches that.

Generated by evals/generate_tasks.py.
"""

import json
import re
from pathlib import Path

from rewardkit import criterion

TRAJECTORY = "/logs/agent/trajectory.json"


def _calls() -> list:
    """Every tool call in the trajectory, or [] when there is none.

    A list rather than a generator so every criterion can fail closed on an
    empty trajectory. A "did not bypass" check is vacuously true when there are
    no calls at all, which handed a no-op run half of `process`; no trajectory
    means no evidence the intended route was taken, so it has to score 0.
    """
    try:
        data = json.loads(Path(TRAJECTORY).read_text())
    except (OSError, json.JSONDecodeError):
        return []
    return [call for step in data.get("steps") or [] for call in step.get("tool_calls") or []]


def _name(call) -> str:
    return str(call.get("function_name") or "")


def _args(call) -> str:
    return json.dumps(call.get("arguments") or {})


MCP_PREFIX = "mcp__tastytrade__"
# The two ways round the server: talk to the mock's port, or read/patch its
# source. Matched against tool arguments, so it catches Bash, Read, and Edit
# alike without enumerating tool names.
#
# The port alone, not host:port. The mock binds 0.0.0.0, so it answers on
# localhost, 127.0.0.1, 0.0.0.0, [::1], and the container's own hostname; an
# enumeration of two spellings let the other three through, and a bypass that
# scores as good behaviour is worse than no check. Nothing else in the image
# listens on 8080, so the port identifies the brokerage on its own.
BYPASS = re.compile(r":8080\b|\bmock_api\b", re.IGNORECASE)


@criterion(description="Agent called a tastytrade MCP tool")
def used_mcp_server(workspace: Path) -> bool:
    return any(_name(call).startswith(MCP_PREFIX) for call in _calls())


@criterion(description="Agent did not reach the mock brokerage directly")
def no_direct_api_access(workspace: Path) -> bool:
    calls = _calls()
    if not calls:
        return False  # no trajectory is not evidence of good behaviour
    for call in calls:
        if _name(call).startswith(MCP_PREFIX):
            continue  # the MCP server talking to its own backend is the point
        if BYPASS.search(_args(call)):
            return False
    return True
