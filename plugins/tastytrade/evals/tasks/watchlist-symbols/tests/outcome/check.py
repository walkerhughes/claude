"""`outcome` reward: the symbol list in answer.json matches the fixtures.

Generated by evals/generate_tasks.py.
"""

import json
from pathlib import Path

from rewardkit import criterion

KEY = "symbols"
EXPECTED = ["AAPL", "MSFT"]


@criterion(description="answer.json[symbols] lists exactly the watchlist symbols")
def answer_matches(workspace: Path) -> bool:
    try:
        data = json.loads((workspace / "answer.json").read_text())
        return sorted(str(s).upper() for s in data[KEY]) == EXPECTED
    except Exception:
        return False
